"""Build examples/demo-dashboard.yaml (templates + views for every card and flame style) for the demo fireplaces."""
import pathlib
root = pathlib.Path(__file__).resolve().parents[1]
tpl = (root / "button-card/modern-flames-templates.yaml").read_text()
units = ["living_room_fireplace", "patio_fireplace", "den_fireplace", "bedroom_fireplace"]
styles = ["glow", "shader", "illustrated"]

def bc(t, u, ind, style=None, extra=""):
    p = " " * ind
    vs = ", ".join(x for x in [f"flame_style: {style}" if style else "", extra] if x)
    v = f"{p}  variables: {{{vs}}}\n" if vs else ""
    return f"{p}- type: custom:button-card\n{p}  template: {t}\n{p}  entity: climate.{u}\n{v}"

def view(title, path, body):
    return f"  - title: {title}\n    path: {path}\n    type: panel\n    cards:\n      - type: vertical-stack\n        cards:\n{body}"

v = ["views:"]
for s in styles:
    v.append(view(f"Hearth {s}", f"hearth-{s}", "".join(bc("modern_flames_hearth", u, 10, s) for u in units[:3])))
for s in styles:
    v.append(view(f"Overview {s}", f"overview-{s}", "          - type: grid\n            columns: 2\n            square: false\n            cards:\n" + "".join(bc("modern_flames_tile", u, 14, s) for u in units)))
v.append(view("Chips", "chips", "".join(bc("modern_flames_chips", u, 10) for u in units)))
for s in styles:
    v.append(view(f"Studio {s}", f"studio-{s}", f"          - type: custom:modern-flames-card\n            entity: climate.living_room_fireplace\n            flame_style: {s}\n"))
# customisation examples
v.append(view("Custom", "custom",
    bc("modern_flames_hearth", units[0], 10, "glow", "compact: true, controls: [power, heat, timer], radius: 14px") +
    bc("modern_flames_hearth", units[1], 10, "shader", "controls: [power, scene, speed, sync], show_zones: false, intensity: 1.3") +
    bc("modern_flames_hearth", units[2], 10, "glow", "colors: {flame: '#ff7a1a', embers: '#ff3b0a', downlight: '#ffd28a'}, speed_sync: false, controls: [power, heat]")))
v.append(view("Studio compact", "studio-compact", "          - type: custom:modern-flames-card\n            entity: climate.patio_fireplace\n            flame_style: shader\n            compact: true\n            radius: 18px\n"))
v.append(view("Studio demo", "studio-demo", "          - type: custom:modern-flames-card\n            demo: true\n            name: Demo Fireplace\n"))
body = tpl[tpl.index("\nbutton_card_templates:") + 1:]
(root / "examples/demo-dashboard.yaml").write_text("# Generated by tools/gen_demo_dashboard.py: a demo dashboard for the fake fireplaces in demo/.\ntitle: Modern Flames\n" + body + "\n" + "\n".join(v))
print("ok")
